// One source, three layers, two surfaces. Everything downstream is generated.
//
//   node scripts/build-tokens.mjs
//
// reads  tokens/wildflower-wind.tokens.json
// writes features/wildflower-wind/tokens.json        (ratios computed, never typed)
//        features/wildflower-wind/wildflower-wind-tokens.css
//        public/brand/wildflower-wind/wildflower-wind-tokens.css
//        public/brand/wildflower-wind/wildflower-wind-tokens.json
//        index.html                                  (between the token markers)

import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const src = join(root, 'tokens', 'wildflower-wind.tokens.json')
const t = JSON.parse(await readFile(src, 'utf8'))

/* ── colour maths ────────────────────────────────────────────────────────── */

const lum = (hex) => {
  const h = hex.replace('#', '')
  const f = h.length === 3 ? [...h].map((c) => c + c).join('') : h.slice(0, 6)
  const [r, g, b] = [0, 2, 4].map((i) => {
    const c = parseInt(f.slice(i, i + 2), 16) / 255
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4
  })
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}
const ratio = (a, b) => {
  const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x)
  return (hi + 0.05) / (lo + 0.05)
}
const px = (n) => Number(n.toFixed(2))

const P = Object.fromEntries(t.primitives.map((p) => [p.name, p.value]))
const D = Object.fromEntries(t.darkPrimitives.map((p) => [p.name, p.value]))

/* ── the pairs, each with the job it is allowed to do ────────────────────── */

const pairs = [
  ['ink on the pane — body and display', P.ink, P.glass, 'text'],
  ['ink on haze — body and display', P.ink, P.haze, 'text'],
  ['muted on the pane — metadata', P.muted, P.glass, 'text'],
  ['muted on haze — metadata', P.muted, P.haze, 'text'],
  ['signal on the pane — accent text', P.signal, P.glass, 'text'],
  ['signal on haze — accent text', P.signal, P.haze, 'text'],
  ['glass on signal — button label', P.glass, P.signal, 'text'],
  ['ink on petal — text on the tinted pane', P.ink, P.petal, 'text'],
  ['haze on ink — type on the night field', P.haze, P.ink, 'text'],
  ['leaf on haze — second tint, text-safe', P.leaf, P.haze, 'text'],
  ['gold on haze — graphic only', P.gold, P.haze, 'graphic'],
  ['sky on haze — surface only', P.sky, P.haze, 'surface'],
  ['ink on haze — dark scope body', D.ink, D.haze, 'text'],
  ['muted on the pane — dark scope metadata', D.muted, D.glass, 'text'],
  ['signal on haze — dark scope accent', D.signal, D.haze, 'text'],
]

const contrast = pairs.map(([label, fg, bg, job]) => ({ label, fg, bg, ratio: px(ratio(fg, bg)), job, pass: ratio(fg, bg) >= 4.5 }))

/* ── tokens.json — what the gates read ───────────────────────────────────── */

const outJson = {
  ...t,
  meta: { ...t.meta, contrastPairs: contrast.length, failingPairs: contrast.filter((c) => !c.pass).length },
  contrast,
}

/* ── the CSS ─────────────────────────────────────────────────────────────── */

const kebab = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-')

const primitiveBlock = (list, indent = '  ') => list.map((p) => `${indent}--wi-${kebab(p.name)}: ${p.value};`).join('\n')
const semanticBlock = (list, indent = '  ') => list.map((s) => `${indent}--wi-${kebab(s.name)}: ${s.value};`).join('\n')

const css = `/* Wildflower Wind — generated by scripts/build-tokens.mjs from tokens/wildflower-wind.tokens.json.
   Do not edit: edit the source, then run the script. Three layers, always:
   primitive (the material) → semantic (the job) → component (the only place a
   button knows its own colour). A night surface is a scope, not a second palette. */

.wi-scope {
${primitiveBlock(t.primitives)}

${semanticBlock(t.semantic.light)}

  /* type — one stack per voice, never a one-off */
  --wi-font-display: var(--font-display, 'Instrument Serif'), 'Iowan Old Style', Georgia, serif;
  --wi-font-reading: var(--font-reading, 'Instrument Sans'), 'Helvetica Neue', system-ui, sans-serif;
  --wi-font-mono: var(--font-mono, 'IBM Plex Mono'), ui-monospace, 'SFMono-Regular', monospace;

${t.type.map((e) => `  --wi-${kebab(e.name)}-s: ${e.size}px;`).join('\n')}
${t.type.map((e) => `  --wi-${kebab(e.name)}-lh: ${e.leading};`).join('\n')}
${t.type.map((e) => `  --wi-${kebab(e.name)}-ls: ${e.tracking}em;`).join('\n')}
${t.type.map((e) => `  --wi-${kebab(e.name)}-w: ${e.weight};`).join('\n')}

${t.space.map((s, i) => `  --wi-space-${i + 1}: ${s}px;`).join('\n')}

${Object.entries(t.radius).map(([k, v]) => `  --wi-radius-${k}: ${v}px;`).join('\n')}

${t.motion.map((m) => `  --wi-motion-${kebab(m.name)}: ${m.value};`).join('\n')}

  /* 3 · component */
  --wi-button-bg: var(--wi-text-primary);
  --wi-button-ink: var(--wi-surface-page);
  --wi-pane-bg: var(--wi-surface-pane);
  --wi-pane-line: var(--wi-edge-lit);
  --wi-pane-blur: 28px;
  --wi-pane-saturate: 150%;

  /* one lit edge, one long shadow. Glass catches light at the top-left and
     drops it at the bottom-right, and a surface that does both evenly is a card. */
  --wi-pane-shadow:
    0 1px 0 0 var(--wi-edge-lit) inset,
    0 -1px 0 0 rgb(255 255 255 / 0.18) inset,
    0 30px 70px -34px rgb(42 30 51 / 0.42),
    0 2px 8px -4px rgb(42 30 51 / 0.16);
  --wi-pane-shadow-lift:
    0 1px 0 0 rgb(255 255 255 / 0.9) inset,
    0 44px 90px -40px rgb(42 30 51 / 0.5),
    0 4px 14px -6px rgb(42 30 51 / 0.2);
}

/* night — the same names, different values. Nothing above this line changes. */
html[data-wildflower-wind='dark'] .wi-scope,
html[data-wildflower-wind='dark'] {
${primitiveBlock(t.darkPrimitives)}
}
`

/* ── write ───────────────────────────────────────────────────────────────── */

await mkdir(join(root, 'features', 'wildflower-wind'), { recursive: true })
await mkdir(join(root, 'public', 'brand', 'wildflower-wind'), { recursive: true })

await writeFile(join(root, 'features', 'wildflower-wind', 'tokens.json'), JSON.stringify(outJson, null, 2) + '\n')
await writeFile(join(root, 'features', 'wildflower-wind', 'wildflower-wind-tokens.css'), css)
await writeFile(join(root, 'public', 'brand', 'wildflower-wind', 'wildflower-wind-tokens.css'), css)
await writeFile(join(root, 'public', 'brand', 'wildflower-wind', 'wildflower-wind-tokens.json'), JSON.stringify(outJson, null, 2) + '\n')

// the page carries the same block and the same numbers, so a single file is still
// the whole thing and nothing in it can drift from the source
try {
  let page = await readFile(join(root, 'index.html'), 'utf8')
  page = page.replace(/(\/\* @tokens:start \*\/)[\s\S]*?(\/\* @tokens:end \*\/)/, `$1\n${css}\n$2`)
  const data = JSON.stringify(
    contrast.map((c) => ({ label: c.label.replace(/ —.*$/, ''), fg: c.fg, bg: c.bg, ratio: c.ratio, job: c.job })),
  )
  page = page.replace(
    /(<!-- @contrast:start -->)[\s\S]*?(<!-- @contrast:end -->)/,
    `$1\n<script type="application/json" id="wiContrast">${data}</script>\n$2`,
  )
  await writeFile(join(root, 'index.html'), page)

  // the same page at the route path, with the asset prefixes lifted three levels
  const routed = page
    .replace(/(src|href)="assets\//g, '$1="../../../assets/')
    .replace(/(src|href)="public\/brand\//g, '$1="../../../public/brand/')
    .replace(/href="docs\//g, 'href="../../../docs/')
    .replace(/href="tokens\//g, 'href="../../../tokens/')
    .replace(/href="brand\//g, 'href="../../../brand/')
    .replace(/url\('assets\//g, "url('../../../assets/")
  await writeFile(join(root, 'app', 'design-system', 'wildflower-wind', 'page.html'), routed)
} catch (e) {
  /* the page does not exist yet — the next build will pick it up */
}

const fails = contrast.filter((c) => !c.pass)
console.log(`tokens → ${contrast.length} pairs computed, ${fails.length} published as failing`)
for (const f of fails) console.log(`  FAIL  ${f.label.padEnd(48)} ${f.ratio.toFixed(2)}:1`)
