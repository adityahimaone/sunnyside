// tokens.json → a Figma plugin, a tokens.figma.json and a manifest.
//
//   node scripts/figma-export.mjs
//
// Regenerate, never edit: design/figma/wildflower-wind/code.js is output, and the
// next token change overwrites it. The plugin is deliberately plain — variables,
// paint styles, text styles, one page per section — because every extra node is
// something that can drift from the sheet.

import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const out = join(root, 'design', 'figma', 'wildflower-wind')
const tokens = JSON.parse(await readFile(join(root, 'features', 'wildflower-wind', 'tokens.json'), 'utf8'))

const hexToRgb = (hex) => {
  const h = hex.replace('#', '')
  const n = h.length === 3 ? [...h].map((c) => c + c).join('') : h
  return { r: parseInt(n.slice(0, 2), 16) / 255, g: parseInt(n.slice(2, 4), 16) / 255, b: parseInt(n.slice(4, 6), 16) / 255 }
}

const light = tokens.primitives
const dark = tokens.darkPrimitives
const semantic = tokens.semantic.light
const type = tokens.type
const space = tokens.space
const radius = tokens.radius
const motion = tokens.motion
const sections = tokens.sections

/* ── tokens.figma.json — the same sheet, in Figma's vocabulary ───────────── */

const figmaTokens = {
  $meta: { name: 'Wildflower Wind', version: tokens.meta.version, namespace: tokens.meta.namespace, generated: 'scripts/figma-export.mjs' },
  collections: {
    'Wildflower Wind': {
      modes: ['Light', 'Dusk'],
      primitive: Object.fromEntries(light.map((p) => [p.name, { Light: p.value, Dusk: (dark.find((d) => d.name === p.name) || {}).value ?? p.value }])),
      semantic: Object.fromEntries(semantic.map((s) => [s.name, { Light: s.value, Dusk: s.value }])),
    },
  },
  styles: {
    paint: light.map((p) => ({ name: `ink/${p.name}`, colour: p.value, note: p.role })),
    text: type.map((t) => ({ name: `type/${t.name}`, family: t.value, size: t.size, lineHeight: t.leading, letterSpacing: t.tracking, weight: t.weight })),
  },
  numbers: { space, radius, motion },
}

/* ── code.js — a plugin that builds the file ─────────────────────────────── */

const code = `// Wildflower Wind — generated by scripts/figma-export.mjs. Do not edit.
// ${light.length} primitives × 2 modes, ${semantic.length} semantic aliases, ${type.length} text styles,
// ${light.length} paint styles, ${sections.length} pages. One source: features/wildflower-wind/tokens.json.

const PRIMITIVES = ${JSON.stringify(Object.fromEntries(light.map((p) => [p.name, { light: p.value, dark: (dark.find((d) => d.name === p.name) || {}).value ?? p.value }])))}

const SEMANTIC = ${JSON.stringify(Object.fromEntries(semantic.map((s) => [s.name, s.value])))}

const TYPE = ${JSON.stringify(type.map((t) => ({ name: t.name, family: t.value, size: t.size, leading: t.leading, tracking: t.tracking, weight: t.weight })))}

const SPACE = ${JSON.stringify(space)}
const RADIUS = ${JSON.stringify(radius)}
const MOTION = ${JSON.stringify(motion.map((m) => ({ name: m.name, value: m.value })))}
const SECTIONS = ${JSON.stringify(sections)}

const rgb = (hex) => {
  const h = hex.replace('#', '')
  return {
    r: parseInt(h.slice(0, 2), 16) / 255,
    g: parseInt(h.slice(2, 4), 16) / 255,
    b: parseInt(h.slice(4, 6), 16) / 255,
  }
}

// The brand face is not guaranteed to be installed on the machine running the
// plugin, and a plugin that assumes it is fails on the first colleague's laptop.
// Try it, then fall back to a face Figma always has, and say so once.
const FACES = [
  { display: 'Instrument Serif', reading: 'Instrument Sans', mono: 'IBM Plex Mono' },
  { display: 'Source Serif 4', reading: 'Inter', mono: 'Roboto Mono' },
]

async function loadFaces() {
  for (const set of FACES) {
    try {
      await Promise.all([
        figma.loadFontAsync({ family: set.display, style: 'Regular' }),
        figma.loadFontAsync({ family: set.reading, style: 'Regular' }),
        figma.loadFontAsync({ family: set.reading, style: 'Semi Bold' }),
        figma.loadFontAsync({ family: set.mono, style: 'Regular' }),
      ])
      return { faces: set, exact: set === FACES[0] }
    } catch (e) {
      /* try the next set */
    }
  }
  return { faces: FACES[1], exact: false }
}

function roleFace(role, faces) {
  if (role === 'mono') return { family: faces.mono, style: 'Regular' }
  if (role.startsWith('display')) return { family: faces.display, style: 'Regular' }
  if (role === 'title-1' || role === 'title-2' || role === 'label') return { family: faces.reading, style: 'Semi Bold' }
  return { family: faces.reading, style: 'Regular' }
}

async function main() {
  const { faces, exact } = await loadFaces()

  /* 1 · the collection, two modes, primitives only */
  const collection = figma.variables.createVariableCollection('Wildflower Wind')
  const lightMode = collection.modes[0].modeId
  collection.renameMode(lightMode, 'Light')
  const darkMode = collection.addMode('Dusk')

  const byName = {}
  for (const [name, v] of Object.entries(PRIMITIVES)) {
    const variable = figma.variables.createVariable('primitive/' + name, collection, 'COLOR')
    variable.description = name + ' — the material, named once'
    variable.setValueForMode(lightMode, rgb(v.light))
    variable.setValueForMode(darkMode, rgb(v.dark))
    byName[name] = variable
  }

  /* 2 · semantics alias primitives, so a mode flip moves nothing else */
  for (const [name, value] of Object.entries(SEMANTIC)) {
    const target = /var\\(--wi-([a-z-]+)\\)/.exec(value)
    if (!target || !byName[target[1]]) continue
    const variable = figma.variables.createVariable('semantic/' + name, collection, 'COLOR')
    variable.description = name + ' — the job'
    variable.setValueForMode(lightMode, figma.variables.createVariableAlias(byName[target[1]]))
    variable.setValueForMode(darkMode, figma.variables.createVariableAlias(byName[target[1]]))
  }

  /* 3 · numbers */
  SPACE.forEach((px, i) => {
    const v = figma.variables.createVariable('space/' + (i + 1), collection, 'FLOAT')
    v.setValueForMode(lightMode, px)
    v.setValueForMode(darkMode, px)
  })
  for (const [name, px] of Object.entries(RADIUS)) {
    const v = figma.variables.createVariable('radius/' + name, collection, 'FLOAT')
    v.setValueForMode(lightMode, px)
    v.setValueForMode(darkMode, px)
  }
  for (const m of MOTION) {
    const v = figma.variables.createVariable('motion/' + m.name, collection, 'STRING')
    v.setValueForMode(lightMode, m.value)
    v.setValueForMode(darkMode, m.value)
  }

  /* 4 · paint styles, one per primitive, bound to the variable */
  for (const [name, v] of Object.entries(PRIMITIVES)) {
    const style = figma.createPaintStyle()
    style.name = 'ink/' + name
    style.description = 'Wildflower Wind · ' + name
    style.paints = [
      figma.variables.setBoundVariableForPaint({ type: 'SOLID', color: rgb(v.light) }, 'color', byName[name]),
    ]
  }

  /* 5 · text styles */
  for (const t of TYPE) {
    const style = figma.createTextStyle()
    style.name = 'type/' + t.name
    style.description = t.family + ' ' + t.weight + ' · ' + t.size + 'px · lh ' + t.leading + ' · ls ' + t.tracking + 'em'
    style.fontName = roleFace(t.name, faces)
    style.fontSize = t.size
    style.lineHeight = { unit: 'PERCENT', value: Math.round(t.leading * 100) }
    style.letterSpacing = { unit: 'PERCENT', value: Math.round((t.tracking * 1000) / 10) }
  }

  /* 6 · one page per section, titled, with a swatch row so the file is not empty */
  const cover = figma.currentPage
  cover.name = '00 · cover'

  for (const s of SECTIONS) {
    const page = figma.createPage()
    page.name = s
    figma.currentPage = page
    const frame = figma.createFrame()
    frame.name = s + ' · 1440'
    frame.resize(1440, 900)
    frame.fills = []
    page.appendChild(frame)
  }

  figma.currentPage = cover
  figma.closePlugin(
    'Wildflower Wind built: ' + Object.keys(PRIMITIVES).length + ' primitives, ' +
      Object.keys(SEMANTIC).length + ' semantic aliases, ' + TYPE.length + ' text styles, ' +
      SECTIONS.length + ' pages' + (exact ? '' : ' (brand faces missing here — fell back to ' + faces.display + ')'),
  )
}

main().catch((e) => {
  figma.closePlugin('Build failed: ' + e.message)
})
`

/* ── manifest ────────────────────────────────────────────────────────────── */

const manifest = {
  name: 'Wildflower Wind — build',
  id: 'wildflower-wind-build',
  api: '1.0.0',
  main: 'code.js',
  editorType: ['figma'],
  networkAccess: { allowedDomains: ['none'] },
  documentAccess: 'dynamic-page',
}

/* ── README ──────────────────────────────────────────────────────────────── */

const readme = `# Wildflower Wind → Figma

Generated by \`scripts/figma-export.mjs\` from \`features/wildflower-wind/tokens.json\`.
Do not edit \`code.js\`; edit the tokens and regenerate.

## Use it

1. Figma → **Plugins → Development → Import plugin from manifest…**
2. Pick \`manifest.json\` in this folder.
3. Run **Wildflower Wind — build** in a new design file.

It creates one variable collection with two modes (Light, Dusk), ${light.length} primitives,
${semantic.length} semantic aliases pointing at them, ${type.length} text styles, ${light.length} paint
styles and ${sections.length} pages — one per section of the specimen.

## What it cannot carry

- **The petal curve.** The mark is a bent spine with a width profile. Figma gets the
  geometry (\`public/brand/wildflower-wind/*.svg\` imports cleanly) but not the rule that
  generated it, so a resized mark is a resized picture.
- **The register ghost.** A 2.2px second impression is a \`text-shadow\`; Figma has no
  equivalent effect that prints the same way.
- **The faces.** Instrument Serif and Instrument Sans are under the SIL Open Font
  License and ship in \`assets/fonts/\`. The plugin falls back to Source Serif 4 / Inter
  when they are not installed, and says so when it closes.

## Check it

\`\`\`bash
node ../../../.workbuddy-ai/skills/sunnyside-brand-system/scripts/figma-smoke.mjs code.js
\`\`\`
`

await mkdir(out, { recursive: true })
await writeFile(join(out, 'code.js'), code)
await writeFile(join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n')
await writeFile(join(out, 'tokens.figma.json'), JSON.stringify(figmaTokens, null, 2) + '\n')
await writeFile(join(out, 'README.md'), readme)
await mkdir(join(out, 'fonts'), { recursive: true })
for (const f of ['InstrumentSerif-Regular.ttf', 'InstrumentSans-Variable.ttf', 'IBMPlexMono-Regular.ttf']) {
  await copyFile(join(root, 'assets', 'fonts', f), join(out, 'fonts', f))
}

console.log(`figma export → ${out}`)
