#!/usr/bin/env node
/**
 * figma-bind — emit the thin Figma plugin that reconnects imported layers to
 * the brand system.
 *
 *   node scripts/figma-bind.mjs --slug vesper --root . --out design/figma/vesper-bind
 *   node scripts/figma-bind.mjs --slug vesper --root . --tokens path/to/tokens.json --check
 *   node scripts/figma-bind.mjs --slug vesper --root . --infer-layout
 *
 * Why this exists: html.to.design / Stitch / Builder.io already create Figma
 * Auto Layout from HTML. Doop's Copy for Figma does not, and neither importer
 * binds your OKLCH tokens to Figma variables. figma-forge.mjs builds the system
 * (variables, styles, components); this plugin binds a *page* to that system.
 * It is a post-processor, not a second HTML-to-Figma converter.
 *
 * `--infer-layout` opts into Figma's inferredAutoLayout heuristic for flat
 * imports. Leave it off after html.to.design — re-applying layoutMode reflows
 * children that already have correct auto layout.
 *
 * Zero dependencies. `--check` prints what it resolved and writes nothing.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { basename, dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { findTokens, readTokens } from './lib/tokens.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const TEMPLATE = resolve(HERE, '..', 'templates', 'figma-bind-plugin.js')

const args = process.argv.slice(2)
const one = (name, fallback) => {
  const i = args.indexOf(`--${name}`)
  return i === -1 ? fallback : args[i + 1]
}
const has = (name) => args.includes(`--${name}`)

function locateTokens(root, slug, explicit) {
  if (explicit) {
    const p = resolve(explicit)
    if (!existsSync(p)) throw new Error(`--tokens path does not exist: ${p}`)
    return p
  }
  const extra = [
    join(root, 'src', 'tokens.json'),
    join(root, slug, 'src', 'tokens.json'),
    join(root, 'src', slug, 'tokens.json'),
  ]
  return extra.find(existsSync) ?? findTokens(root, slug)
}

const slug = one('slug', '')
const root = resolve(one('root', '.'))
const tokensArg = one('tokens', null)
const inferLayout = has('infer-layout')

if (!slug) {
  console.error(`Usage:
  node scripts/figma-bind.mjs --slug <slug> [--root .] [--tokens <path>] [--out <dir>] [--infer-layout] [--check]`)
  process.exit(1)
}

const tokensPath = locateTokens(root, slug, tokensArg)
if (!tokensPath) throw new Error(`Could not find tokens.json for slug "${slug}" under ${root} — pass --tokens <path>`)

const parsed = readTokens(tokensPath)
const palette = parsed.primitives
  .filter((p) => p.hex)
  .map((p) => ({ name: String(p.name), hex: String(p.hex) }))

if (!palette.length) {
  throw new Error(`${tokensPath} resolved shape "${parsed.shape}" but no hex primitives were found`)
}

const brand = parsed.name || slug.charAt(0).toUpperCase() + slug.slice(1)
const namespace = parsed.namespace ? parsed.namespace.replace(/^-+|-+$/g, '') : slug.slice(0, 2)
const DATA = {
  brand,
  slug,
  collection: brand + ' / Colour',
  namespace,
  inferLayout,
  palette,
}

const out = resolve(one('out', join(root, 'design', 'figma', `${slug}-bind`)))

if (has('check')) {
  console.log(JSON.stringify({
    slug, brand, root, tokens: tokensPath, shape: parsed.shape,
    palette: palette.length, collection: DATA.collection,
    inferLayout, out, template: TEMPLATE,
  }, null, 2))
  console.log('\n  Nothing written.')
  process.exit(0)
}

const template = await readFile(TEMPLATE, 'utf8')
if (!template.includes('const DATA = __DATA__;')) {
  throw new Error('template is missing the __DATA__ slot: ' + TEMPLATE)
}
const code = template.replace('__DATA__', () => JSON.stringify(DATA, null, 2))

const manifest = {
  name: `${brand} — bind`,
  id: `${slug}-bind`,
  api: '1.0.0',
  main: 'code.js',
  editorType: ['figma'],
  networkAccess: { allowedDomains: ['none'] },
  documentAccess: 'dynamic-page',
}

const readme = `# ${brand} → Figma bind

Generated by \`scripts/figma-bind.mjs\` from \`${basename(tokensPath)}\`.
Do not edit \`code.js\`; edit the tokens and regenerate.

## Use it

1. Run the **build** plugin from \`figma-forge.mjs\` in a Figma file (variables,
   paint/text styles, components).
2. Import \`<slug>-figma.html\` with html.to.design / Stitch to Figma / Builder.io.
   Those importers create native frames with Auto Layout.
3. Select the imported frames (or nothing, to walk the whole page) and run
   **${brand} — bind**.

It matches each SOLID fill and stroke to a local COLOR variable by measured RGB,
and each text node to a local text style by font size + family. No colour is
guessed by name. Layers whose colour is not in the token file are left alone.

## Fallback

If no local COLOR variables exist, the plugin creates a \`${DATA.collection}\`
collection with the ${palette.length} primitive colours from the token file and
says so on close. That is colours only — run the build plugin for modes,
aliases, styles and components.

## Auto layout

${inferLayout
    ? 'Enabled. Frames with no auto layout get Figma\'s `inferredAutoLayout` heuristic applied. Use this on flat imports (Doop Copy for Figma). Regenerate without `--infer-layout` before running it over html.to.design output.'
    : 'Off. The HTML importer is expected to create auto layout. Regenerate with `--infer-layout` if you are repairing a flat Doop import — applying layoutMode to frames that already reflow correctly will move their children.'}

## Check it

\`\`\`bash
node scripts/figma-bind-smoke.mjs ${join(out, 'code.js')}
\`\`\`
`

await mkdir(out, { recursive: true })
await writeFile(join(out, 'code.js'), code, 'utf8')
await writeFile(join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n', 'utf8')
await writeFile(join(out, 'README.md'), readme, 'utf8')

console.log(`  ✓ ${brand} → ${out}`)
console.log(`    code.js · manifest.json · README.md · ${palette.length} colours · inferLayout=${inferLayout}`)
