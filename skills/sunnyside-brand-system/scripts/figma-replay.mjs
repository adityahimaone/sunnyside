#!/usr/bin/env node
/**
 * figma-replay — emit the Figma plugin that rebuilds an HTML sheet natively.
 *
 *   node scripts/figma-replay.mjs --brand Vesper --slug vesper \
 *     --manifest design/figma/vesper.manifest.json --out design/figma/vesper-replay
 *
 * The HTML sheet measures its own DOM (getComputedStyle + getBoundingClientRect)
 * and copies a `sunnyside/figma-manifest` JSON. This generator packages the
 * replay runtime and, when --manifest is given, embeds that JSON as a seed in
 * the plugin UI so the flow is one click inside Figma.
 *
 * Built from the sheet: Auto Layout frames, live text, rectangles, SVG vectors,
 * named components. Built from tokens.json: variable collections, paint styles
 * bound to them, and text styles. Not a general CSS parser — one known schema.
 *
 * Zero dependencies. `--check` prints what it resolved and writes nothing.
 */
import { copyFile, mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { basename, dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const TEMPLATES = resolve(HERE, '..', 'templates')

const args = process.argv.slice(2)
const one = (name, fallback) => {
  const i = args.indexOf(`--${name}`)
  return i === -1 ? fallback : args[i + 1]
}
const has = (name) => args.includes(`--${name}`)

const slug = one('slug', '')
const brand = one('brand', slug ? slug.charAt(0).toUpperCase() + slug.slice(1) : '')
const root = resolve(one('root', '.'))
const manifestArg = one('manifest', null)
const out = resolve(one('out', join(root, 'design', 'figma', `${slug || 'brand'}-replay`)))

if (!slug || !brand) {
  console.error(`Usage:
  node scripts/figma-replay.mjs --slug <slug> --brand "<Name>" [--manifest <path>] [--out <dir>] [--check]`)
  process.exit(1)
}

const manifestPath = manifestArg ? resolve(manifestArg) : null
if (manifestPath && !existsSync(manifestPath)) throw new Error(`manifest not found: ${manifestPath}`)

let seed = ''
let seedInfo = null
if (manifestPath) {
  const raw = await readFile(manifestPath, 'utf8')
  const parsed = JSON.parse(raw)
  if (parsed.kind !== 'sunnyside/figma-manifest') throw new Error('manifest kind is not sunnyside/figma-manifest')
  seed = JSON.stringify(parsed)
  seedInfo = { sheets: parsed.sheets?.length ?? 0, nodes: parsed.nodes ?? 0, brand: parsed.brand, size: seed.length }
}

if (has('check')) {
  console.log(JSON.stringify({
    slug, brand, out, manifest: manifestPath, seed: seedInfo,
    pluginTemplate: join(TEMPLATES, 'figma-replay-plugin.js'),
    uiTemplate: join(TEMPLATES, 'figma-replay-ui.html'),
  }, null, 2))
  console.log('\n  Nothing written.')
  process.exit(0)
}

const plugin = await readFile(join(TEMPLATES, 'figma-replay-plugin.js'), 'utf8')
const ui = await readFile(join(TEMPLATES, 'figma-replay-ui.html'), 'utf8')
const safeSeed = seed.replace(/</g, '\\u003c')
const uiHtml = ui.replace('__BRAND__', () => brand).replace('__MANIFEST__', () => safeSeed)

const figmaManifest = {
  name: `${brand} — replay`,
  id: `${slug}-replay`,
  api: '1.0.0',
  main: 'code.js',
  ui: 'ui.html',
  editorType: ['figma'],
  networkAccess: { allowedDomains: ['none'] },
  documentAccess: 'dynamic-page',
}

/* A .fig stores family names, not font data, and a plugin cannot install a
 * font. Ship the installable faces next to the plugin so "the text looks
 * wrong" has a one-drag answer. woff2 is skipped: Font Book will not take it. */
const fontDirs = [
  join(root, 'assets', 'fonts'),
  join(root, 'public', 'brand', slug),
  join(root, 'brand', slug),
]
const fontOut = join(out, 'fonts')
let fontCount = 0
for (const dir of fontDirs) {
  if (!existsSync(dir)) continue
  let entries = []
  try { entries = await readdir(dir) } catch (e) { continue }
  for (const f of entries) {
    if (!/\.(ttf|otf)$/i.test(f)) continue
    try {
      await mkdir(fontOut, { recursive: true })
      await copyFile(join(dir, f), join(fontOut, f))
      fontCount++
    } catch (e) { /* a font that will not copy is not fatal */ }
  }
}

const readme = `# ${brand} — Figma replay

Generated by \`scripts/figma-replay.mjs\`. Do not edit \`code.js\`.

## Use it

1. Open the generated \`<slug>-figma.html\` sheet in a browser.
2. Click **Copy for Figma** in the top bar (or run \`scripts/figma-manifest.mjs\`
   to write the manifest to disk and seed it into this plugin).
3. In Figma: **Plugins → Development → Import plugin from manifest…** and pick
   \`${join(out, 'manifest.json')}\`.
4. Run **${brand} — replay**, then **Build in Figma**. Leave **Replace existing
   generated pages** checked when re-importing into a file that already has a
   generated set — it removes only the pages this plugin recreates, never your
   own pages. Uncheck it to append a second copy on purpose.
   Leave **Raise text below 12px to 12px** checked for legible labels; uncheck
   it if you need the sheet's exact type sizes.
   **Sheet 08 · Patterns & Tokens stays optional** — the canonical manifest
   always carries all 8 sheets, but that page is off in Figma by default.

## Migrate an existing file

If the file already has a flat **Doop / html.to.design** import, open this plugin
and click **Upgrade existing pages** instead of rebuilding. It walks the flat
layers in place and binds SOLID fills to this kit's colour variables and TEXT
layers to text styles. Generated pages are skipped, so a second run reports
zero changes. Tick **Infer Auto Layout on flat frames** only if you accept that
Figma's heuristic may reflow a frame.

## Re-running is safe

Variables, collections, paint styles, text styles and effect styles are looked
up by name and updated in place — re-running never leaves a second
\`Brand / Colour\` collection behind. Every generated \`NN · …\` page is removed
and rebuilt; pages you made yourself are untouched.

${seedInfo
    ? `A seed manifest is embedded (${seedInfo.sheets} sheets, ${seedInfo.nodes} nodes, ${seedInfo.size.toLocaleString()} chars), so the textarea is pre-filled — just click Build.`
    : 'No seed manifest was embedded. Paste the JSON from **Copy for Figma** into the textarea.'}

## Fonts

A \`.fig\` stores family names, not font data, and a plugin cannot install a font.
${fontCount ? `The ${fontCount} installable face(s) this brand ships are copied to \`fonts/\` — drag them onto Font Book once, then rebuild.` : 'No `.ttf`/`.otf` faces were found next to this brand; install the families named in `tokens.json` before building.'}
Without them Figma substitutes Inter, which is why type can look wrong while
the layout still holds. The plugin reports how many faces it had to fall back to.

## What it builds

- **Auto Layout** — HORIZONTAL / VERTICAL / GRID frames with \`itemSpacing\`,
  \`padding*\`, alignment, wrap, \`layoutGrow\` (FILL) and absolute children.
  Spacing and padding are bound to FLOAT variables where the value matches.
- **Variables** — primitives, three 10-step ramps, semantic surfaces, plus
  spacing and radius. Any colour the DOM uses but the token file omits gets an
  \`Auto/#RRGGBB\` variable, so **every** solid fill ends up bound.
- **Paint / text / effect / grid styles**, all idempotently upserted by name.
  Text with no matching type role gets a style minted from its own metrics, so
  binding never changes how the type looks.
- **Real components** — variant sets (\`State=Primary\`, \`Tone=Danger\`…),
  descriptions, and live instances in a \`◆ Component Library\` frame beside
  each sheet.
- **Live text**, rectangles, SVG vectors and a canonical 1440px capture that is
  identical no matter how wide the browser window is.

## Why not just use an HTML importer

Importers infer flow from CSS and never bind your tokens. This plugin reads a
manifest emitted by a page we control, so results are deterministic and include
variables, styles and components. It does not parse arbitrary CSS or JavaScript.

## Check it

\`\`\`bash
node scripts/figma-replay-smoke.mjs ${join(out, 'code.js')}
\`\`\`
`

await mkdir(out, { recursive: true })
await writeFile(join(out, 'code.js'), plugin, 'utf8')
await writeFile(join(out, 'ui.html'), uiHtml, 'utf8')
await writeFile(join(out, 'manifest.json'), JSON.stringify(figmaManifest, null, 2) + '\n', 'utf8')
await writeFile(join(out, 'README.md'), readme, 'utf8')

console.log(`  ✓ ${brand} → ${out}`)
console.log(`    code.js · ui.html · manifest.json · README.md${fontCount ? ` · ${fontCount} installable font(s)` : ''}${seedInfo ? ` · seed ${seedInfo.sheets} sheets / ${seedInfo.nodes} nodes` : ' · no seed'}`)
