import { chromium } from '@playwright/test'
const browser = await chromium.launch({ channel: 'chrome' })
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } })
await page.goto('http://localhost:3001/', { waitUntil: 'networkidle', timeout: 60000 })
await page.waitForTimeout(2800)
await page.screenshot({ path: '/tmp/k-mb1280.jpg', type: 'jpeg', quality: 80 })
await page.screenshot({ path: '/tmp/k-pills.jpg', type: 'jpeg', quality: 90, clip: { x: 60, y: 600, width: 640, height: 180 } })
await page.screenshot({ path: '/tmp/k-header.jpg', type: 'jpeg', quality: 90, clip: { x: 0, y: 0, width: 1280, height: 90 } })
await page.screenshot({ path: '/tmp/k-rail.jpg', type: 'jpeg', quality: 90, clip: { x: 100, y: 380, width: 1080, height: 200 } })
await browser.close()
console.log('ok')
