#!/usr/bin/env node
/**
 * Generate the Cove token stylesheet and public JSON from one source:
 * features/cove/tokens.json.
 *
 *   node scripts/generate-cove-tokens.mjs
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises'

const source = JSON.parse(await readFile('features/cove/tokens.json', 'utf8'))

const property = (name) => `--cv-${name}`
const lines = (tokens) =>
  tokens.map(({ name, value }) => `  ${property(name)}: ${value};`).join('\n')
const block = (selector, body) => `${selector} {\n${body}\n}\n`

const staticTokens = [
  ...source.type,
  ...source.space,
  ...source.radius,
  ...source.motion,
]

const shared = [
  '  /* Theme DNA: the mark, the glass and the fields read this object */',
  Object.entries(source.theme)
    .map(([name, value]) => `  --cv-dna-${name}: ${value};`)
    .join('\n'),
  '',
  '  /* Primitive */',
  lines(source.primitives),
  '',
  '  /* Type, space, radius, motion */',
  lines(staticTokens),
].join('\n')

const deep = [
  '  /* Semantic — Deep (default) */',
  lines(source.semantic.dark),
  '',
  '  /* Component — Deep */',
  lines(source.components.dark),
].join('\n')

const frost = [
  '  /* Semantic — Frost */',
  lines(source.semantic.light),
  '',
  '  /* Component — Frost */',
  lines(source.components.light),
].join('\n')

const css = `/* Generated by scripts/generate-cove-tokens.mjs — edit tokens.json. */
/* Three layers: primitive → semantic → component. Namespaced --cv-* so it
   cannot collide with the archive's --ss-* or Vitrine's --vt-*. */

${block(
  '.cv-scope',
  [
    shared,
    '',
    deep,
    '',
    '  background: var(--cv-bg);',
    '  color: var(--cv-fg);',
    '  font-family: var(--cv-font-reading);',
    '  min-height: 100vh;',
    '  color-scheme: dark;',
  ].join('\n'),
)}
${block(
  "html[data-cove='frost'] .cv-scope",
  [frost, '', '  color-scheme: light;'].join('\n'),
)}
`

await mkdir('public/brand/cove', { recursive: true })
await writeFile('features/cove/cove-tokens.css', css)
await writeFile('public/brand/cove/cove-tokens.css', css)
await writeFile(
  'public/brand/cove/cove-tokens.json',
  JSON.stringify(source, null, 2) + '\n',
)

const count =
  Object.keys(source.theme).length +
  source.primitives.length +
  source.semantic.dark.length +
  source.semantic.light.length +
  source.components.dark.length +
  source.components.light.length +
  staticTokens.length
console.log(`cove-tokens.css — ${count} declarations`)
