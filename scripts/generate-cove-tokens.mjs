#!/usr/bin/env node
/**
 * Generate the Cove token stylesheet and public JSON from features/cove/tokens.json.
 *
 *   node scripts/generate-cove-tokens.mjs
 *
 * Cove is night-first: the base block carries the night ramp, and the daylight
 * ramp is an override on `html[data-cove='day']`. That is the opposite of the
 * other cases, and it is deliberate — the system is read after dark.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises'

const source = JSON.parse(await readFile('features/cove/tokens.json', 'utf8'))

const property = (name) => `--cv-${name}`
const lines = (tokens) =>
  tokens.map(({ name, value }) => `  ${property(name)}: ${value};`).join('\n')
const block = (selector, body) => `${selector} {\n${body}\n}\n`

const staticTokens = [...source.type, ...source.space, ...source.radius, ...source.motion]

const shared = [
  '  /* Theme DNA: the mark, the panels and the fields read this object */',
  Object.entries(source.theme)
    .map(([name, value]) => `  --cv-dna-${name}: ${value};`)
    .join('\n'),
  '',
  '  /* Primitive */',
  lines(source.primitives),
  '',
  '  /* Type, space, radius, motion */',
  lines(staticTokens),
].join('\n')

const night = [
  '  /* Semantic — Night (the default surface) */',
  lines(source.semantic.dark),
  '',
  '  /* Component — Night */',
  lines(source.components.dark),
].join('\n')

const day = [
  '  /* Semantic — Daylight */',
  lines(source.semantic.light),
  '',
  '  /* Component — Daylight */',
  lines(source.components.light),
].join('\n')

const css = `/* Generated by scripts/generate-cove-tokens.mjs — edit tokens.json. */
/* Three layers: primitive → semantic → component. Namespaced --cv-* */

${block(
  '.cv-scope',
  [
    shared,
    '',
    night,
    '',
    '  background: var(--cv-bg);',
    '  color: var(--cv-fg);',
    '  font-family: var(--cv-font-reading);',
    '  min-height: 100vh;',
    '  color-scheme: dark;',
  ].join('\n'),
)}
${block(
  "html[data-cove='day'] .cv-scope, .cv-scope[data-cove='day']",
  [day, '', '  color-scheme: light;'].join('\n'),
)}
`

await mkdir('public/brand/cove', { recursive: true })
await writeFile('features/cove/cove-tokens.css', css)
await writeFile('public/brand/cove/cove-tokens.css', css)
await writeFile('public/brand/cove/cove-tokens.json', JSON.stringify(source, null, 2) + '\n')

const declarations = (css.match(/--cv-[a-z0-9-]+\s*:/g) || []).length
console.log(`cove-tokens.css — ${declarations} declarations written`)
