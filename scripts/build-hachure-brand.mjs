/**
 * Hachure brand assets — one source, no hand-edited output.
 *
 *   node scripts/build-hachure-brand.mjs
 *
 * Reads  features/hachure/tokens.json
 *        design/brand/hachure/assets/wordmark-path.json
 * Writes features/hachure/hachure-tokens.css        (imported by the route)
 *        features/hachure/brand-paths.ts            (mark geometry for React)
 *        public/brand/hachure/hachure-tokens.{css,json}
 *        public/brand/hachure/{mark,mark-compact,wordmark,lockup}.svg
 *        public/brand/hachure/favicons/favicon{-16,-32,-180}.svg + favicon.svg
 *        design/brand/hachure/{mark,wordmark}.svg   (sources, same bytes)
 *
 * The wordmark path comes from scripts/hachure-wordmark.py — the logotype is
 * drawn once from Geist Mono at 700 and never set as live text.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const TOKENS = join(ROOT, 'features/hachure/tokens.json')
const PUBLIC = join(ROOT, 'public/brand/hachure')
const DESIGN = join(ROOT, 'design/brand/hachure')

mkdirSync(join(PUBLIC, 'favicons'), { recursive: true })

/* ---------- contrast, measured not typed -------------------------------- */

const channel = (c) => {
  const v = c / 255
  return v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4
}
const luminance = (hex) => {
  const n = parseInt(hex.replace('#', ''), 16)
  return 0.2126 * channel((n >> 16) & 255) + 0.7152 * channel((n >> 8) & 255) + 0.0722 * channel(n & 255)
}
const ratio = (a, b) => {
  const x = luminance(a)
  const y = luminance(b)
  return (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05)
}
const level = (r) => (r >= 7 ? 'AAA' : r >= 4.5 ? 'AA' : r >= 3 ? 'AA large' : 'Fail')

/* ---------- tokens ------------------------------------------------------ */

const tokens = JSON.parse(readFileSync(TOKENS, 'utf8'))

const valueOf = (theme, name) => {
  const pool = theme === 'light' ? tokens.semantic.light : tokens.semantic.dark
  return pool.find((t) => t.name === name)?.value
}

tokens.contrast = tokens.pairs.map((pair) => {
  const a = valueOf(pair.theme, pair.a)
  const b = valueOf(pair.theme, pair.b)
  if (!a || !b) throw new Error(`unknown token in pair: ${pair.a} / ${pair.b} (${pair.theme})`)
  const r = Number(ratio(a, b).toFixed(2))
  return { label: pair.label, theme: pair.theme, a, b, ratio: r, level: level(r), use: pair.use }
})

writeFileSync(TOKENS, JSON.stringify(tokens, null, 2) + '\n')

const vars = (pool) => pool.map((t) => `  --hx-${t.name}: ${t.value};`).join('\n')
const primitives = tokens.primitives.map((t) => `  --hx-${t.name}: ${t.value};`).join('\n')
const tones = (theme) =>
  tokens.tones[theme].map((v, i) => `  --hx-tone-${i + 1}: ${v};`).join('\n')

/* Type, space and motion live in the same source as the colours: the type
   scale is a decision, and a decision that exists only in a stylesheet is one
   nobody can quote. */
const FACES = {
  mono: 'var(--font-geist-mono, ui-monospace), ui-monospace, Menlo, Consolas, monospace',
  sans: 'var(--font-geist, system-ui), system-ui, "Helvetica Neue", Arial, sans-serif',
}
const typeVars = tokens.type
  .map((t) =>
    [
      `  --hx-${t.role}-size: ${t.size};`,
      `  --hx-${t.role}-leading: ${t.leading};`,
      `  --hx-${t.role}-track: ${t.tracking};`,
      `  --hx-${t.role}-weight: ${t.weight};`,
      `  --hx-${t.role}-face: ${FACES[t.face]};`,
    ].join('\n'),
  )
  .join('\n')
const spaceVars = tokens.space.map((t) => `  --hx-space-${t.name}: ${t.value};`).join('\n')
const motionVars = tokens.motion.map((t) => `  --hx-dur-${t.name}: ${t.value};`).join('\n')
const componentVars = tokens.component
  .map((t) => `  --hx-${t.name}: ${t.value};`)
  .join('\n')

const CSS = `/**
 * Hachure — generated by scripts/build-hachure-brand.mjs
 * Edit features/hachure/tokens.json, then re-run. Never hand-edit this file.
 *
 * Tones 1–7 are the dither ramp, darkest last. Tone 1 is the paper itself,
 * which is why the range can dissolve into the page instead of fading out of it.
 */

:root,
.hx-scope,
[data-hachure-root][data-theme="light"] {
${primitives}

${vars(tokens.semantic.light)}

${tones('light')}

${typeVars}

${spaceVars}

${motionVars}

${componentVars}

  --hx-ease: cubic-bezier(0.22, 1, 0.36, 1);
}

[data-hachure-root][data-theme="dark"] {
${vars(tokens.semantic.dark)}

${tones('dark')}
}
`

writeFileSync(join(ROOT, 'features/hachure/hachure-tokens.css'), CSS)
writeFileSync(join(PUBLIC, 'hachure-tokens.css'), CSS)
writeFileSync(join(PUBLIC, 'hachure-tokens.json'), JSON.stringify(tokens, null, 2) + '\n')

/* ---------- the mark: a rising ridge of solid bars -------------------- */

const round = (n) => Number(n.toFixed(2))

/**
 * v2.3: relief drawn by weight, not by thin lines.
 *
 * Four solid wedge-bars rise left to right and thicken as they rise; the gaps
 * are negative channels (5.3 units on the 64 grid). A lichen diamond sits on
 * the summit. No circle, no enclosing ring, no strokes. The compact drops to
 * three bars and widens the channels; `mono` collapses the apex to currentColor.
 */
const FULL = {
  box: 64,
  bars:
    'M2 56V36L10 42V56Z M15.3 56V26L25.3 32V56Z M30.6 56V16L42.6 22V56Z M47.9 56V8L61.9 14V56Z',
  apex: 'M54.9 2L61.9 8L54.9 14L47.9 8Z',
}
const COMPACT = {
  box: 32,
  bars: 'M2 30V20L8 24V30Z M11 30V14L19 18V30Z M22 30V8L31 12V30Z',
  apex: 'M26.5 1L31 8L26.5 15L22 8Z',
}

function markInner(v, apexFill = '#B8CC3B') {
  return `<path d="${v.bars}" fill="var(--hx-mark-ink, #141413)"/><path d="${v.apex}" fill="${apexFill}"/>`
}

const markSVG = (v, size, apexFill = '#B8CC3B') =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${v.box} ${v.box}" width="${size}" height="${size}" role="img" aria-label="Hachure">${markInner(v, apexFill)}</svg>
`

const mark = markSVG(FULL, 64)
const compact = markSVG(COMPACT, 32)
const mono = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="64" height="64" role="img" aria-label="Hachure mono">${markInner(FULL, 'currentColor')}</svg>
`

/* ---------- the wordmark ------------------------------------------------- */

const word = JSON.parse(readFileSync(join(DESIGN, 'assets/wordmark-path.json'), 'utf8'))
const WM_H = 200
const WM_W = round((word.width / word.height) * WM_H)
const WM_SCALE = round(WM_H / word.height)
const WM_X = round(-parseFloat(word.viewBox.split(' ')[0]))
const WM_Y = round(-parseFloat(word.viewBox.split(' ')[1]))

const wordmark = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WM_W} ${WM_H}" width="${WM_W}" height="${WM_H}" role="img" aria-label="hachure">
  <!-- Geist Mono 700, outlined by scripts/hachure-wordmark.py. Never set as live text. -->
  <g transform="scale(${WM_SCALE}) translate(${WM_X} ${WM_Y})">
    <path d="${word.d}" fill="var(--hx-ink, #16211B)"/>
  </g>
</svg>
`

/* ---------- the lockup --------------------------------------------------- */

const LOCK_MARK = 56
const LOCK_GAP = 16
const LOCK_WM_H = 34
const LOCK_WM_W = round((word.width / word.height) * LOCK_WM_H)
const LOCK_W = round(LOCK_MARK + LOCK_GAP + LOCK_WM_W + 2)
const LOCK_H = LOCK_MARK

const lockup = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${LOCK_W} ${LOCK_H}" width="${LOCK_W}" height="${LOCK_H}" role="img" aria-label="Hachure">
  <g transform="translate(0 0) scale(${round(LOCK_MARK / 64)})" color="var(--hx-ink, #141413)">${markInner(FULL)}</g>
  <g transform="translate(${round(LOCK_MARK + LOCK_GAP)} ${round((LOCK_H - LOCK_WM_H) / 2)}) scale(${round(LOCK_WM_H / word.height)}) translate(${WM_X} ${WM_Y})">
    <path d="${word.d}" fill="var(--hx-ink, #141413)"/>
  </g>
</svg>
`

/* ---------- write -------------------------------------------------------- */

const write = (path, body) => writeFileSync(path, body)
write(join(PUBLIC, 'mark.svg'), mark)
write(join(PUBLIC, 'mark-compact.svg'), compact)
write(join(PUBLIC, 'mark-mono.svg'), mono)
write(join(PUBLIC, 'glyph.svg'), mark)
write(join(PUBLIC, 'wordmark.svg'), wordmark)
write(join(PUBLIC, 'lockup.svg'), lockup)
write(join(DESIGN, 'mark.svg'), mark)
write(join(DESIGN, 'mark-compact.svg'), compact)
write(join(DESIGN, 'mark-mono.svg'), mono)
write(join(DESIGN, 'wordmark.svg'), wordmark)

/* Favicons: opaque paper, compact 3-bar drawing at 16/32, full 4-bar at 180. */
const favicon = (size) => {
  const v = size <= 32 ? COMPACT : FULL
  const scale = round(size / v.box)
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}">
  <rect width="${size}" height="${size}" fill="#F2F4EE"/>
  <g transform="scale(${scale})" color="#141413">${markInner(v)}</g>
</svg>
`
}
for (const size of [16, 32, 180]) write(join(PUBLIC, `favicons/favicon-${size}.svg`), favicon(size))
write(join(PUBLIC, 'favicons/favicon.svg'), favicon(32))

/* Geometry for React. */
write(
  join(ROOT, 'features/hachure/brand-paths.ts'),
  `/* Generated by scripts/build-hachure-brand.mjs. Do not edit. */

export const MARK = ${JSON.stringify(FULL)} as const
export const COMPACT = ${JSON.stringify(COMPACT)} as const
export const WORDMARK_D =
  '${word.d}'
export const WORDMARK_VIEWBOX = '${word.viewBox}'
export const WORDMARK_W = ${WM_W}
export const WORDMARK_H = ${WM_H}
export const WORDMARK_RATIO = ${round(WM_W / WM_H)}
export const LOCKUP_W = ${LOCK_W}
export const LOCKUP_H = ${LOCK_H}
`,
)

console.log(`tokens   ${tokens.semantic.light.length} light / ${tokens.semantic.dark.length} dark / ${tokens.contrast.length} measured pairs`)
console.log(`mark     64 grid, four wedge bars + apex; compact three bars`)
console.log(`wordmark ${WM_W} × ${WM_H} from ${word.text}`)
console.log(`lockup   ${LOCK_W} × ${LOCK_H}`)
const fails = tokens.contrast.filter((c) => c.level === 'Fail')
console.log(`failing  ${fails.length ? fails.map((f) => `${f.label} ${f.ratio}:1`).join(', ') : 'none'}`)
