#!/usr/bin/env node
/**
 * Generate the portable Cove form kit: one CSS file and one demo page.
 *
 *   node scripts/generate-cove-forms.mjs
 *
 * v1.0 of this script emitted 500 lines of kit built on a `--cv-field-*` layer
 * that no longer exists. This version reads the component layer that actually
 * ships (`--cv-btn-*`, `--cv-field-*`, `--cv-radius-*`, `--cv-duration-*`) and
 * refuses to write a declaration that names a token the token sheet does not
 * declare — a kit that references a dead variable is worse than no kit.
 */
import { readFile, writeFile } from 'node:fs/promises'

const tokens = JSON.parse(await readFile('features/cove/tokens.json', 'utf8'))
const css = await readFile('features/cove/cove-tokens.css', 'utf8')

const declared = new Set(
  [...css.matchAll(/^\s*(--cv-[\w-]+):/gm)].map((match) => match[1]),
)

const used = new Set()
/** `var(--cv-x)` through this helper so every reference can be checked. */
const v = (name) => {
  used.add(name)
  return `var(${name})`
}

const sheet = `/* Generated by scripts/generate-cove-forms.mjs — edit tokens.json. */
/* Cove ${tokens.meta.version} · ${tokens.meta.material} · ${tokens.theme.edge} edge,
   ${tokens.theme.radius} radius, ${tokens.theme.ring} ring. No raw colours:
   every value below resolves through the token sheet, so the kit follows the
   night and day ramps without a second stylesheet. */

.cv-form {
  display: grid;
  gap: ${v('--cv-space-5')};
  color: ${v('--cv-fg')};
  font-family: ${v('--cv-font-reading')};
  font-size: ${v('--cv-scale-body')};
  line-height: ${v('--cv-leading-body')};
}

.cv-form *,
.cv-form *::before,
.cv-form *::after {
  box-sizing: border-box;
}

.cv-form fieldset {
  margin: 0;
  padding: 0;
  border: 0;
  display: grid;
  gap: ${v('--cv-space-4')};
}

.cv-form legend {
  padding: 0 0 ${v('--cv-space-2')};
  font-family: ${v('--cv-font-mono')};
  font-size: ${v('--cv-scale-label')};
  letter-spacing: ${v('--cv-tracking-label')};
  text-transform: uppercase;
  color: ${v('--cv-muted')};
}

.cv-field {
  display: grid;
  gap: ${v('--cv-space-2')};
  min-width: 0;
}

.cv-label {
  display: flex;
  align-items: baseline;
  justify-content: space-between;
  gap: ${v('--cv-space-3')};
  font-family: ${v('--cv-font-mono')};
  font-size: ${v('--cv-scale-label')};
  letter-spacing: 0.09em;
  text-transform: uppercase;
  color: ${v('--cv-muted')};
}

.cv-hint {
  font-size: ${v('--cv-scale-caption')};
  color: ${v('--cv-muted')};
  margin: 0;
}

.cv-error {
  font-family: ${v('--cv-font-mono')};
  font-size: ${v('--cv-scale-caption')};
  color: ${v('--cv-alarm')};
  margin: 0;
}

.cv-input,
.cv-select,
.cv-textarea {
  width: 100%;
  min-height: 40px;
  padding: 0 ${v('--cv-space-3')};
  border: 1px solid ${v('--cv-field-edge')};
  border-radius: ${v('--cv-radius-sm')};
  background: ${v('--cv-field-bg')};
  color: ${v('--cv-fg')};
  font: inherit;
  font-size: ${v('--cv-scale-small')};
  font-variant-numeric: tabular-nums;
  transition:
    border-color ${v('--cv-duration-fast')} ${v('--cv-ease-out')},
    background ${v('--cv-duration-fast')} ${v('--cv-ease-out')};
}

.cv-textarea {
  min-height: 96px;
  padding: ${v('--cv-space-3')};
  line-height: 1.55;
  resize: vertical;
}

.cv-input::placeholder,
.cv-textarea::placeholder {
  color: ${v('--cv-muted')};
}

.cv-input:hover,
.cv-select:hover,
.cv-textarea:hover {
  border-color: ${v('--cv-line-strong')};
}

.cv-input:focus-visible,
.cv-select:focus-visible,
.cv-textarea:focus-visible {
  outline: 2px solid ${v('--cv-field-focus')};
  outline-offset: 1px;
  border-color: ${v('--cv-field-focus')};
}

.cv-field[data-invalid='true'] .cv-input,
.cv-field[data-invalid='true'] .cv-select,
.cv-field[data-invalid='true'] .cv-textarea {
  border-color: ${v('--cv-alarm')};
}

.cv-check {
  display: flex;
  align-items: flex-start;
  gap: ${v('--cv-space-3')};
  font-size: ${v('--cv-scale-small')};
  color: ${v('--cv-fg')};
}

.cv-check input {
  width: 16px;
  height: 16px;
  margin: 3px 0 0;
  accent-color: ${v('--cv-signal')};
}

.cv-actions {
  display: flex;
  flex-wrap: wrap;
  align-items: center;
  gap: ${v('--cv-space-3')};
}

.cv-button {
  display: inline-flex;
  align-items: center;
  justify-content: center;
  gap: ${v('--cv-space-2')};
  min-height: 40px;
  padding: 0 ${v('--cv-space-4')};
  border-radius: ${v('--cv-radius-sm')};
  border: 1px solid transparent;
  font-family: ${v('--cv-font-reading')};
  font-size: ${v('--cv-scale-small')};
  font-weight: 500;
  cursor: pointer;
  transition:
    background ${v('--cv-duration-fast')} ${v('--cv-ease-out')},
    border-color ${v('--cv-duration-fast')} ${v('--cv-ease-out')};
}

.cv-button[data-variant='primary'] {
  background: ${v('--cv-btn-primary-bg')};
  border-color: ${v('--cv-btn-primary-bg')};
  color: ${v('--cv-btn-primary-fg')};
}

.cv-button[data-variant='secondary'] {
  background: ${v('--cv-btn-secondary-bg')};
  border-color: ${v('--cv-field-edge')};
  color: ${v('--cv-btn-secondary-fg')};
}

.cv-button[data-variant='ghost'] {
  background: transparent;
  color: ${v('--cv-muted')};
}

.cv-button[data-variant='ghost']:hover {
  color: ${v('--cv-fg')};
  border-color: ${v('--cv-line')};
}

.cv-button:hover {
  filter: brightness(1.06);
}

.cv-button:focus-visible {
  outline: 2px solid ${v('--cv-signal')};
  outline-offset: 2px;
}

.cv-button[disabled] {
  opacity: 0.5;
  cursor: not-allowed;
  filter: none;
}
`

const missing = [...used].filter((name) => !declared.has(name))
if (missing.length) {
  console.error(`Token sheet does not declare: ${missing.join(', ')}`)
  process.exit(1)
}

const html = `<!doctype html>
<html lang="en" data-cove="night">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>Cove — form kit</title>
    <link rel="stylesheet" href="./cove-tokens.css" />
    <link rel="stylesheet" href="./cove-forms.css" />
    <style>
      body {
        margin: 0;
        padding: 48px 24px;
        background: var(--cv-bg);
        color: var(--cv-fg);
        font-family: var(--cv-font-reading);
        color-scheme: dark;
      }
      main {
        width: min(520px, 100%);
        margin-inline: auto;
      }
      h1 {
        font-family: var(--cv-font-display);
        font-size: 28px;
        font-weight: 600;
        letter-spacing: -0.03em;
        margin: 0 0 6px;
      }
      .lede {
        margin: 0 0 32px;
        color: var(--cv-muted);
        font-size: 14px;
        line-height: 1.6;
      }
      .cv-form {
        padding: 22px;
        border: 1px solid var(--cv-line);
        border-radius: var(--cv-radius-md);
        background: var(--cv-plate);
      }
    </style>
  </head>
  <body>
    <main>
      <h1>Log a reading</h1>
      <p class="lede">
        The portable kit: one stylesheet, the token sheet, no JavaScript and no
        raw colour. Every control is at least 40px tall.
      </p>

      <form class="cv-form" novalidate>
        <fieldset>
          <legend>Station</legend>

          <div class="cv-field">
            <label class="cv-label" for="cv-station">
              Station id <span>required</span>
            </label>
            <input
              class="cv-input"
              id="cv-station"
              name="station"
              value="Cove 04 · north arm"
              autocomplete="off"
            />
            <p class="cv-hint">The id printed on the post, not the beach name.</p>
          </div>

          <div class="cv-field" data-invalid="true">
            <label class="cv-label" for="cv-level">Water level</label>
            <input
              class="cv-input"
              id="cv-level"
              name="level"
              value="1.4x"
              inputmode="decimal"
              aria-invalid="true"
              aria-describedby="cv-level-error"
            />
            <p class="cv-error" id="cv-level-error">
              A value has to be a number. Try 1.42.
            </p>
          </div>

          <div class="cv-field">
            <label class="cv-label" for="cv-unit">Unit</label>
            <select class="cv-select" id="cv-unit" name="unit">
              <option>metres</option>
              <option>feet</option>
            </select>
          </div>

          <div class="cv-field">
            <label class="cv-label" for="cv-note">Note</label>
            <textarea
              class="cv-textarea"
              id="cv-note"
              name="note"
              placeholder="What the water was doing."
            ></textarea>
          </div>

          <label class="cv-check">
            <input type="checkbox" name="threshold" checked />
            <span>Mark this reading if it crossed 1.20 m.</span>
          </label>
        </fieldset>

        <div class="cv-actions">
          <button class="cv-button" data-variant="primary" type="submit">
            Log this reading
          </button>
          <button class="cv-button" data-variant="secondary" type="button">
            Export
          </button>
          <button class="cv-button" data-variant="ghost" type="button">
            Discard
          </button>
        </div>
      </form>
    </main>
  </body>
</html>
`

await writeFile('public/brand/cove/cove-forms.css', sheet)
await writeFile('public/brand/cove/cove-forms.html', html)
console.log(
  `cove-forms.css (${used.size} tokens, all declared) + cove-forms.html`,
)
