#!/usr/bin/env node
/**
 * Generate the Strand token stylesheet and public JSON from features/strand/tokens.json.
 *
 *   node scripts/generate-strand-tokens.mjs
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises'

const source = JSON.parse(await readFile('features/strand/tokens.json', 'utf8'))

const property = (name) => `--st-${name}`
const lines = (tokens) =>
  tokens.map(({ name, value }) => `  ${property(name)}: ${value};`).join('\n')
const block = (selector, body) => `${selector} {\n${body}\n}\n`

const staticTokens = [
  ...source.type,
  ...source.space,
  ...source.radius,
  ...source.motion,
]

const shared = [
  '  /* Theme DNA: the mark, the coastline vista and the fields read this object */',
  Object.entries(source.theme)
    .map(([name, value]) => `  --st-dna-${name}: ${value};`)
    .join('\n'),
  '',
  '  /* Primitive */',
  lines(source.primitives),
  '',
  '  /* Type, space, radius, motion */',
  lines(staticTokens),
].join('\n')

const dune = [
  '  /* Semantic — Dune (default light) */',
  lines(source.semantic.light),
  '',
  '  /* Component — Dune */',
  lines(source.components.light),
].join('\n')

const night = [
  '  /* Semantic — Night Tide */',
  lines(source.semantic.dark),
  '',
  '  /* Component — Night Tide */',
  lines(source.components.dark),
].join('\n')

const css = `/* Generated by scripts/generate-strand-tokens.mjs — edit tokens.json. */
/* Three layers: primitive → semantic → component. Namespaced --st-* */

${block(
  '.st-scope',
  [
    shared,
    '',
    dune,
    '',
    '  background: var(--st-bg);',
    '  color: var(--st-fg);',
    '  font-family: var(--st-font-reading);',
    '  min-height: 100vh;',
    '  color-scheme: light;',
  ].join('\n'),
)}
${block(
  "html[data-strand='night'] .st-scope, .st-scope[data-strand='night']",
  [night, '', '  color-scheme: dark;'].join('\n'),
)}
`

await mkdir('public/brand/strand', { recursive: true })
await writeFile('features/strand/strand-tokens.css', css)
await writeFile('public/brand/strand/strand-tokens.css', css)
await writeFile(
  'public/brand/strand/strand-tokens.json',
  JSON.stringify(source, null, 2) + '\n',
)

const count =
  Object.keys(source.theme).length +
  source.primitives.length +
  source.semantic.dark.length +
  source.semantic.light.length +
  source.components.dark.length +
  source.components.light.length +
  staticTokens.length
console.log(`strand-tokens.css — ${count} declarations written`)
