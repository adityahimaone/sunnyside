#!/usr/bin/env node
/**
 * Generate the Vitrine token stylesheet and public JSON from one source:
 * features/vitrine/tokens.json. Run after editing tokens.json:
 *
 *   node scripts/generate-vitrine-tokens.mjs
 */
import { readFile, writeFile } from 'node:fs/promises'

const source = JSON.parse(
  await readFile('features/vitrine/tokens.json', 'utf8'),
)

const property = (name) => `--vt-${name}`
const lines = (tokens) =>
  tokens.map(({ name, value }) => `  ${property(name)}: ${value};`).join('\n')
const block = (selector, body) => `${selector} {\n${body}\n}\n`

const staticTokens = [
  ...source.type,
  ...source.space,
  ...source.radius,
  ...source.motion,
]

const shared = [
  '  /* Theme DNA: the mark and the fields read this object */',
  Object.entries(source.theme)
    .map(([name, value]) => `  --vt-dna-${name}: ${value};`)
    .join('\n'),
  '',
  '  /* Primitive */',
  lines(source.primitives),
  '',
  '  /* Type, space, radius, motion */',
  lines(staticTokens),
].join('\n')

const light = [
  '  /* Semantic — light */',
  lines(source.semantic.light),
  '',
  '  /* Component — light */',
  lines(source.components.light),
].join('\n')

const dark = [
  '  /* Semantic — dark */',
  lines(source.semantic.dark),
  '',
  '  /* Component — dark */',
  lines(source.components.dark),
].join('\n')

const bridge = [
  '  /* dithercn bridge: the engine reads these on the shader root */',
  '  --dither-ink: var(--vt-dither-ink);',
  '  --dither-paper: var(--vt-dither-paper);',
  '  --dither-cell: var(--vt-dither-cell);',
  '  --dither-color-signal: var(--vt-signal);',
  '  --dither-color-iris: var(--vt-iris);',
  '  --dither-color-clay: var(--vt-clay);',
  '  --dither-color-mint: var(--vt-mint);',
  '  --dither-color-blue: var(--vt-iris);',
  '  --dither-color-purple: var(--vt-iris-light);',
  '  --dither-color-green: var(--vt-mint);',
  '  --dither-color-pink: var(--vt-clay-light);',
  '  --dither-color-orange: var(--vt-clay-light);',
  '  --dither-color-red: var(--vt-clay);',
  '  --dither-color-grey: var(--vt-muted);',
].join('\n')

const css = `/* Generated by scripts/generate-vitrine-tokens.mjs — edit tokens.json. */
/* Three layers: primitive → semantic → component. Namespaced to avoid the
   archive's --ss-* and shadcn's role tokens. */

${block('.vt-scope', [shared, '', light, '', bridge, '', '  background: var(--vt-bg);', '  color: var(--vt-fg);', '  font-family: var(--vt-font-reading);', '  min-height: 100vh;', '  color-scheme: light;'].join('\n'))}
${block('.dark .vt-scope', [dark, '', '  color-scheme: dark;'].join('\n'))}
`

await writeFile('features/vitrine/vitrine-tokens.css', css)
await writeFile('public/brand/vitrine/vitrine-tokens.css', css)
await writeFile(
  'public/brand/vitrine/vitrine-tokens.json',
  JSON.stringify(source, null, 2) + '\n',
)

const count =
  Object.keys(source.theme).length +
  source.primitives.length +
  source.semantic.light.length +
  source.semantic.dark.length +
  source.components.light.length +
  source.components.dark.length +
  staticTokens.length
console.log(`vitrine-tokens.css — ${count} declarations`)
