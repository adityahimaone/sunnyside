// Generate the app's mark components from the brand SVGs.
//
//   node vesper/scripts/port-marks.mjs <path/to/vesper-marks.tsx>
//
// The proof page inlines these files with a small helper that strips the baked
// fill and sets fill="currentColor", so a mark can be re-inked by whatever colour
// its container has — that is how the reverse tiles work without a second
// drawing. An <img> would lose that, which is why the port keeps them inline.
//
// The component name, viewBox and path data all come from the file; nothing here
// is retyped, so the app and the page cannot drift apart on geometry.

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const brand = resolve(here, '../public/brand/vesper')

const FILES = [
  ['Mark', 'mark.svg'],
  ['MarkCompact', 'mark-compact.svg'],
  ['Glyph', 'glyph.svg'],
  ['Wordmark', 'wordmark.svg'],
  ['Lockup', 'lockup.svg'],
  ['LockupStacked', 'lockup-stacked.svg'],
  ['Icon', 'icon.svg'],
  ['Favicon', 'favicon.svg'],
  ['CastMoon', 'cast/moon.svg'],
  ['CastLamp', 'cast/lamp.svg'],
  ['CastHorizon', 'cast/horizon.svg'],
  ['CastFigure', 'cast/figure.svg'],
  ['CastRay', 'cast/ray.svg'],
  ['CastGrain', 'cast/grain.svg'],
]

const components = FILES.map(([name, file]) => {
  const src = readFileSync(resolve(brand, file), 'utf8')
  const viewBox = src.match(/viewBox="([^"]+)"/)[1]
  const body = src
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/fill="#[0-9a-fA-F]{3,6}"/g, '')
    .replace(/fill-rule="evenodd"/g, '')
    .replace(/<g\s*>/g, '')
    .replace(/<\/g>/g, '')
    .trim()
  // `d` is the only content these files have, but a path may also carry a
  // transform (the outlined wordmark does), so parse the tag rather than assume
  // the attribute order.
  const paths = [...body.matchAll(/<path\b([^>]*?)\/?>/g)].map((m) => {
    const attrs = m[1]
    const d = attrs.match(/\sd="([^"]+)"/)
    if (!d) throw new Error(`${file}: a <path> has no d attribute`)
    const transform = attrs.match(/\stransform="([^"]+)"/)
    return `      <path d="${d[1]}"${transform ? ` transform="${transform[1]}"` : ''} />`
  })
  if (!paths.length) throw new Error(`${file}: no path data found`)
  return `export function ${name}(props: MarkProps) {
  return (
    <svg viewBox="${viewBox}" fill="currentColor" fillRule="evenodd" aria-hidden="true" focusable="false" {...props}>
${paths.join('\n')}
    </svg>
  )
}`
})

const out = `/* Vesper — the mark family as components.

   Generated by vesper/scripts/port-marks.mjs from public/brand/vesper/*.svg.
   Do not hand-edit: change the drawing in the design-system repo, re-run the
   porter, and both the static page and this module move together.

   Every component paints with fill="currentColor" and carries
   aria-hidden="true". A mark is decoration next to its own wordmark; where it
   is the only label, the caller passes an aria-label and role="img". */

import type { SVGProps } from 'react'

export type MarkProps = SVGProps<SVGSVGElement>

${components.join('\n\n')}
`

const dest = process.argv[2]
if (!dest) {
  console.error('usage: node vesper/scripts/port-marks.mjs <path/to/vesper-marks.tsx>')
  process.exit(1)
}
writeFileSync(dest, out)
console.log(`wrote ${FILES.length} mark components, ${out.length} bytes`)
