// The bake-off table. It prints the shipped mark's rank even when that rank is
// not first, which it is not: two concepts survive downscaling better and lost
// on meaning. A scorer that only printed its own winner would be decoration.
function bakeoffBlock() {
  if (!scores) {
    return `<div class="bakeoff"><h3>Eleven concepts, unscored</h3>
      <p class="intro">The scorer has not been run in this checkout. Run <span class="mono">node vesper/scripts/score-bakeoff.mjs</span> and rebuild; no ranking is claimed until then.</p></div>`
  }
  const rows = scores
    .map((s) => {
      const ship = s.id === 'horizon-star'
      const lost = s.failed.length
        ? s.failed.map((f) => esc(f)).join(' · ')
        : 'nothing — clean at 128, 40 and 16'
      return `<tr class="${ship ? 'ship' : ''}">
        <td>${esc(s.name)}${ship ? ' <span class="flag">shipped</span>' : ''}</td>
        <td>${lost}</td>
        <td class="val">${s.score}</td>
      </tr>`
    })
    .join('')
  const shipped = scores.find((s) => s.id === 'horizon-star')
  const rank = scores.findIndex((s) => s.id === 'horizon-star') + 1
  return `
      <div class="bakeoff">
        <h3>Eleven concepts, <em>scored</em>.</h3>
        <p class="intro">Each concept was rasterised at 128, 40 and 16 in a browser and measured: ink coverage at 16px, how many separate pieces survive there, how much of its ink it keeps between 40 and 16, whether parts merge, centroid offset, grid use, and overlap with every other concept. Eight pass-or-fail checks, no weights. <b>${esc(shipped.name)} ranks ${rank} of ${scores.length}</b> — two concepts survive downscaling better and lost anyway, because a scorer can measure whether a shape holds at 16px and cannot measure whether it says <em>lamp</em>.</p>
        <table class="audit scores">
          <thead><tr><th>Concept</th><th>What it loses</th><th>Score</th></tr></thead>
          <tbody>${rows}</tbody>
        </table>
        <p class="bakenote"><span class="mono">node vesper/scripts/score-bakeoff.mjs</span> · rendered in Chrome, measured on the pixel grid, no model involved</p>
      </div>`
}

